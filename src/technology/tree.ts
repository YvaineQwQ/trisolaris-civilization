export const TECH_MAP: Record<string, TechDef> = Object.fromEntries(TECH_DEFS.map((tech) => [tech.id, tech]));

/** 取科技定义；未知 id 返回 undefined。 */
export function getTechDef(id: string): TechDef | undefined {
  return TECH_MAP[id];
}

/** 按分支分组（保持 tier、成本、id 顺序稳定）。 */
export function techsByBranch(branch: TechBranch): TechDef[] {
  return TECH_DEFS.filter((tech) => tech.branch === branch).sort(
    (a, b) => a.tier - b.tier || a.cost - b.cost || a.id.localeCompare(b.id),
  );
}

/** 科技中文名；未知 id 原样返回。 */
export function techName(id: string): string {
  return TECH_MAP[id]?.name ?? id;
}

/** 某科技所属学说；旧内容缺省时按分支推断，保证 UI 永不出现 undefined。 */
export function techSchoolOf(id: string): TechSchool | null {
  const def = TECH_MAP[id];
  if (!def) return null;
  return def.school ?? inferSchool(def);
}

function inferSchool(def: TechDef): TechSchool {
  switch (def.branch) {
    case "astronomy":
      return "observation";
    case "computing":
      return "calculation";
    case "society":
    case "social":
    case "military":
      return "authority";
    case "biology":
      return "ecological";
    case "space":
      return "expansion";
    case "energy":
    case "industry":
    default:
      return "industrial";
  }
}

/** 某科技所属发展大类（未知 id 返回 null）。 */
export function researchCategoryOf(id: string): ResearchCategory | null {
  const def = TECH_MAP[id];
  return def ? TECH_CATEGORY_OF_BRANCH[def.branch] : null;
}

/** 分支所属发展大类。 */
export function branchCategory(branch: TechBranch): ResearchCategory {
  return TECH_CATEGORY_OF_BRANCH[branch];
}

/** 某发展大类下的全部科技。 */
export function techsByCategory(category: ResearchCategory): TechDef[] {
  return TECH_DEFS.filter((tech) => TECH_CATEGORY_OF_BRANCH[tech.branch] === category);
}

/** 互斥教义组元数据；未知组返回 undefined。 */
export function getDoctrineGroupMeta(groupId: string): DoctrineGroupMeta | undefined {
  return DOCTRINE_GROUPS.find((group) => group.id === groupId);
}

/** 某教义组内的科技列表（按 tier/成本排序）。 */
export function doctrineTechs(groupId: string): TechDef[] {
  const meta = getDoctrineGroupMeta(groupId);
  if (!meta) return [];
  return meta.techIds.map((id) => TECH_MAP[id]).filter((def): def is TechDef => Boolean(def));
}

/** 该科技是否属于某个互斥教义组。 */
export function isDoctrineTech(id: string): boolean {
  return Boolean(TECH_MAP[id]?.exclusiveGroup);
}

/** 研发某项科技所需的全部科研点（含硬前置链；requiresAny 取最便宜的一条）。 */
export function techChainCost(id: string, seen: Set<string> = new Set()): number {
  const def = TECH_MAP[id];
  if (!def || seen.has(id)) return 0;
  seen.add(id);
  const hard = def.requires.reduce((sum, req) => sum + techChainCost(req, seen), 0);
  let soft = 0;
  if (def.requiresAny && def.requiresAny.length > 0) {
    const options = def.requiresAny
      .filter((req) => Boolean(TECH_MAP[req]))
      .map((req) => techChainCost(req, new Set(seen)));
    soft = options.length > 0 ? Math.min(...options) : 0;
  }
  return def.cost + hard + soft;
}

/** 某时代（tier）的科技定义列表。 */
export function techsInTier(tier: number): TechDef[] {
  return TECH_DEFS.filter((tech) => tech.tier === tier);
}

/** 某时代可研究的科技（tier <= era）。 */
export function techsAvailableInEra(era: number): TechDef[] {
  return TECH_DEFS.filter((tech) => tech.tier <= era);
}
