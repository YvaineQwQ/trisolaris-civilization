/** id → 定义索引。 */
export const EVENT_DEF_MAP: Record<string, GameEventDef> = Object.fromEntries(
  EVENT_DEFS.map((def) => [def.id, def]),
);

/** 依据 id 取事件定义；未知 id 返回 null。 */
export function getEventDef(id: string): GameEventDef | null {
  return EVENT_DEF_MAP[id] ?? null;
}

/** 按类别筛选事件（UI 分类浏览 / 测试用）。 */
export function eventsByCategory(category: EventCategory): GameEventDef[] {
  return EVENT_DEFS.filter((def) => def.category === category);
}

/** 指定时代可出场（仅按 era 区间，不含其它条件）的事件。 */
export function eventsForEra(era: number): GameEventDef[] {
  const value = Math.max(1, Math.min(5, Math.floor(era)));
  return EVENT_DEFS.filter((def) => value >= def.eraMin && value <= def.eraMax);
}
