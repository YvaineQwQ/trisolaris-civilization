/** 选项构造辅助：让内容表保持紧凑、字段齐全。 */
function ch(
  id: string,
  label: string,
  description: string,
  outcome: string,
  effects: EventEffects,
  extra: { risk?: string; requirements?: EventRequirement } = {},
): EventChoiceDef {
  return { id, label, description, outcome, effects, ...extra };
}

/** 后续事件构造辅助。 */
function fu(
  eventId: string,
  weight = 2,
  delayTurns = 2,
  requirements?: EventRequirement,
): EventFollowUpDef {
  return { eventId, weight, delayTurns, requirements };
}

